-- O valor em aberto nao e campo gravado: e conta feita na hora.
-- Campo desatualiza quando alguem esquece de somar; conta, nao.
CREATE OR REPLACE VIEW VW_CONTRATACAO_FINANCEIRO AS
SELECT
    c.ID                  AS CONTRATACAO_ID,
    c.CLIENTE_ID,
    cli.NOME              AS CLIENTE_NOME,
    cli.CPF               AS CLIENTE_CPF,
    cli.WHATSAPP          AS CLIENTE_WHATSAPP,
    c.DATA_CONTRATACAO,
    c.SITUACAO,
    c.VALOR_TABELA,
    c.DESCONTO,
    c.VALOR_FINAL,
    NVL(pg.TOTAL_PAGO, 0)     AS TOTAL_PAGO,
    NVL(de.TOTAL_DESPESAS, 0) AS TOTAL_DESPESAS,
    c.VALOR_FINAL - NVL(pg.TOTAL_PAGO, 0)                         AS EM_ABERTO,
    c.VALOR_FINAL - NVL(pg.TOTAL_PAGO, 0) - NVL(de.TOTAL_DESPESAS, 0) AS RESULTADO_LIQUIDO
FROM CONTRATACOES c
JOIN CLIENTES cli
    ON cli.ID = c.CLIENTE_ID
-- Agregados em subconsulta, e nao GROUP BY no corpo: assim uma contratacao
-- com 3 pagamentos e 2 despesas nao multiplica linha com linha.
LEFT JOIN (SELECT CONTRATACAO_ID, SUM(VALOR) AS TOTAL_PAGO
             FROM PAGAMENTOS GROUP BY CONTRATACAO_ID) pg
    ON pg.CONTRATACAO_ID = c.ID
LEFT JOIN (SELECT CONTRATACAO_ID, SUM(VALOR) AS TOTAL_DESPESAS
             FROM DESPESAS GROUP BY CONTRATACAO_ID) de
    ON de.CONTRATACAO_ID = c.ID;

COMMENT ON TABLE VW_CONTRATACAO_FINANCEIRO IS 'Situacao financeira por contratacao. Daqui sai quem esta devendo.';


-- Quem esta devendo, que e a primeira coisa que ela olha de manha.
CREATE OR REPLACE VIEW VW_COBRANCAS_ABERTAS AS
SELECT
    CONTRATACAO_ID,
    CLIENTE_ID,
    CLIENTE_NOME,
    CLIENTE_WHATSAPP,
    DATA_CONTRATACAO,
    VALOR_FINAL,
    TOTAL_PAGO,
    EM_ABERTO,
    TRUNC(SYSDATE) - TRUNC(DATA_CONTRATACAO) AS DIAS_DESDE_CONTRATACAO
FROM VW_CONTRATACAO_FINANCEIRO
WHERE EM_ABERTO > 0
  AND SITUACAO <> 'CANCELADO';

COMMENT ON TABLE VW_COBRANCAS_ABERTAS IS 'Contratacoes com saldo a receber, para a cobranca diaria.';
