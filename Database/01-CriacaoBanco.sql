-- =====================================================================
-- GESTOR DE RECURSOS - criacao do banco
-- =====================================================================
-- Alvo: Oracle Autonomous Database (19c+), usuario GESTOR.
-- Ordem: as tabelas sao criadas na ordem das dependencias, entao o
-- script roda de cima para baixo sem erro de chave estrangeira.
--
-- Convencoes adotadas aqui:
--   * VARCHAR2(n CHAR) e nao VARCHAR2(n): "Joao" ocupa 4 caracteres,
--     mas 5 bytes. Sem o CHAR, nome com acento estoura o limite.
--   * Identity em vez de sequence + trigger: menos peca para manter.
--   * Toda constraint tem nome: erro em producao aponta a regra violada,
--     e nao um SYS_C0012345 indecifravel.
--   * ON DELETE CASCADE apenas onde o filho nao existe sozinho.
--     Pagamento e despesa nao tem cascade: dinheiro nao some junto.
--   * Dominios fechados (situacao, forma de pagamento...) em CHECK.
--     A regra mora no banco, nao so na tela.
-- =====================================================================


-- =====================================================================
-- 1. ACESSO E CONFIGURACAO
-- =====================================================================

CREATE TABLE USUARIOS (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME        VARCHAR2(80 CHAR)   NOT NULL,
    LOGIN       VARCHAR2(30 CHAR)   NOT NULL,
    SENHA_HASH  VARCHAR2(200 CHAR)  NOT NULL,
    ATIVO       CHAR(1)             DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_USUARIOS      PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_LOGIN UNIQUE (LOGIN),
    CONSTRAINT CK_USUARIOS_ATIVO CHECK (ATIVO IN ('S','N'))
);

COMMENT ON TABLE USUARIOS IS 'Quem entra no sistema: ela e o pai. Ambos veem tudo.';
COMMENT ON COLUMN USUARIOS.SENHA_HASH IS 'Hash da senha. Senha em texto puro nunca entra aqui.';


-- Linha unica com a qualificacao de quem assina os documentos.
CREATE TABLE ESCRITORIO (
    ID                     NUMBER              DEFAULT 1 NOT NULL,
    NOME                   VARCHAR2(120 CHAR)  NOT NULL,
    NACIONALIDADE          VARCHAR2(40 CHAR),
    ESTADO_CIVIL           VARCHAR2(30 CHAR),
    PROFISSAO              VARCHAR2(120 CHAR),
    RG                     VARCHAR2(20 CHAR),
    RG_ORGAO               VARCHAR2(20 CHAR),
    CPF                    VARCHAR2(11 CHAR),
    REGISTRO_PROFISSIONAL  VARCHAR2(40 CHAR),
    EMAIL                  VARCHAR2(120 CHAR),
    LOGRADOURO             VARCHAR2(150 CHAR),
    NUMERO                 VARCHAR2(20 CHAR),
    COMPLEMENTO            VARCHAR2(60 CHAR),
    BAIRRO                 VARCHAR2(80 CHAR),
    CEP                    VARCHAR2(8 CHAR),
    CIDADE                 VARCHAR2(80 CHAR),
    UF                     VARCHAR2(2 CHAR),
    CIDADE_ASSINATURA      VARCHAR2(80 CHAR),
    CONSTRAINT PK_ESCRITORIO       PRIMARY KEY (ID),
    -- Trava a tabela em uma linha so: o escritorio e um.
    CONSTRAINT CK_ESCRITORIO_LINHA CHECK (ID = 1)
);

COMMENT ON TABLE ESCRITORIO IS 'Dados da despachante que assina procuracoes e recursos.';
COMMENT ON COLUMN ESCRITORIO.REGISTRO_PROFISSIONAL IS 'Registro de despachante documentalista. Vazio ate sair.';
COMMENT ON COLUMN ESCRITORIO.CIDADE_ASSINATURA IS 'Cidade do rodape dos documentos. A data e sempre a da geracao.';


-- =====================================================================
-- 2. CLIENTES E VEICULOS
-- =====================================================================

CREATE TABLE CLIENTES (
    ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME           VARCHAR2(120 CHAR)  NOT NULL,
    CPF            VARCHAR2(11 CHAR)   NOT NULL,
    EMAIL          VARCHAR2(120 CHAR),
    WHATSAPP       VARCHAR2(15 CHAR)   NOT NULL,
    -- CNH: um por cliente e sem historico, entao fica aqui e nao em tabela propria.
    CNH_NUMERO     VARCHAR2(11 CHAR),
    CNH_CATEGORIA  VARCHAR2(5 CHAR),
    CNH_VALIDADE   DATE,
    CNH_REGISTRO   VARCHAR2(20 CHAR),
    -- Os cinco abaixo existem para a procuracao, nao para o processo.
    RG             VARCHAR2(20 CHAR),
    RG_ORGAO       VARCHAR2(20 CHAR),
    NACIONALIDADE  VARCHAR2(40 CHAR),
    ESTADO_CIVIL   VARCHAR2(30 CHAR),
    PROFISSAO      VARCHAR2(120 CHAR),
    OBSERVACOES    VARCHAR2(1000 CHAR),
    ARQUIVADO      CHAR(1)             DEFAULT 'N' NOT NULL,
    DATA_CADASTRO  DATE                DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CLIENTES           PRIMARY KEY (ID),
    CONSTRAINT UK_CLIENTES_CPF       UNIQUE (CPF),
    CONSTRAINT CK_CLIENTES_ARQUIVADO CHECK (ARQUIVADO IN ('S','N')),
    -- CPF entra so com digitos: a formatacao e problema da tela.
    CONSTRAINT CK_CLIENTES_CPF       CHECK (REGEXP_LIKE(CPF, '^[0-9]{11}$'))
);

COMMENT ON TABLE CLIENTES IS 'Cliente do escritorio. Nunca e apagado: usa-se ARQUIVADO.';
COMMENT ON COLUMN CLIENTES.OBSERVACOES IS 'Anotacoes livres. Por decisao da cliente, nao guarda senha de terceiros.';
COMMENT ON COLUMN CLIENTES.ARQUIVADO IS 'S esconde o cliente das listas, preservando o historico.';


-- Um endereco por cliente (RF-04). O UNIQUE no CLIENTE_ID e o que garante o "um".
CREATE TABLE ENDERECOS (
    ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLIENTE_ID   NUMBER              NOT NULL,
    CEP          VARCHAR2(8 CHAR),
    LOGRADOURO   VARCHAR2(150 CHAR)  NOT NULL,
    NUMERO       VARCHAR2(20 CHAR),
    COMPLEMENTO  VARCHAR2(60 CHAR),
    BAIRRO       VARCHAR2(80 CHAR),
    CIDADE       VARCHAR2(80 CHAR)   NOT NULL,
    ESTADO       VARCHAR2(2 CHAR)    NOT NULL,
    CONSTRAINT PK_ENDERECOS         PRIMARY KEY (ID),
    CONSTRAINT UK_ENDERECOS_CLIENTE UNIQUE (CLIENTE_ID),
    CONSTRAINT FK_ENDERECOS_CLIENTE FOREIGN KEY (CLIENTE_ID)
        REFERENCES CLIENTES (ID) ON DELETE CASCADE
);

COMMENT ON TABLE ENDERECOS IS 'Endereco do cliente. Existe para a procuracao e para o recurso.';


CREATE TABLE VEICULOS (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PLACA         VARCHAR2(7 CHAR)    NOT NULL,
    RENAVAM       VARCHAR2(11 CHAR),
    -- Os tres abaixo so aparecem no texto do recurso.
    MARCA_MODELO  VARCHAR2(80 CHAR),
    COR           VARCHAR2(30 CHAR),
    ANO           VARCHAR2(9 CHAR),
    OBSERVACAO    VARCHAR2(200 CHAR),
    CONSTRAINT PK_VEICULOS       PRIMARY KEY (ID),
    CONSTRAINT UK_VEICULOS_PLACA UNIQUE (PLACA)
);

COMMENT ON TABLE VEICULOS IS 'Veiculo identificado pela placa. Pode nao ser do cliente.';
COMMENT ON COLUMN VEICULOS.ANO IS 'Texto porque o documento traz "2019/2019" (fabricacao/modelo).';


-- A ponte cliente-veiculo, com o papel. E por aqui que se responde
-- "de quem e esta placa?", que e a maior dor do escritorio hoje.
CREATE TABLE CLIENTE_VEICULO (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLIENTE_ID  NUMBER            NOT NULL,
    VEICULO_ID  NUMBER            NOT NULL,
    VINCULO     VARCHAR2(20 CHAR) NOT NULL,
    CONSTRAINT PK_CLIENTE_VEICULO      PRIMARY KEY (ID),
    CONSTRAINT UK_CLIENTE_VEICULO      UNIQUE (CLIENTE_ID, VEICULO_ID, VINCULO),
    CONSTRAINT FK_CLIVEI_CLIENTE       FOREIGN KEY (CLIENTE_ID)
        REFERENCES CLIENTES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_CLIVEI_VEICULO       FOREIGN KEY (VEICULO_ID)
        REFERENCES VEICULOS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_CLIVEI_VINCULO       CHECK (VINCULO IN ('PROPRIETARIO','CONDUTOR'))
);

COMMENT ON TABLE CLIENTE_VEICULO IS 'Liga cliente e veiculo com o papel: proprietario ou condutor indicado.';


-- =====================================================================
-- 3. MULTAS E PROCESSOS DE CNH
-- =====================================================================

-- A multa pertence ao VEICULO, nao ao cliente: e o carro que e multado,
-- e e pela placa que a informacao volta do DETRAN.
CREATE TABLE MULTAS (
    ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    VEICULO_ID          NUMBER              NOT NULL,
    AIT                 VARCHAR2(30 CHAR)   NOT NULL,
    ORGAO_AUTUADOR      VARCHAR2(80 CHAR),
    CODIGO_ORGAO        VARCHAR2(20 CHAR),
    DATA_HORA_INFRACAO  DATE,
    LOCAL_INFRACAO      VARCHAR2(200 CHAR),
    ENQUADRAMENTO       VARCHAR2(40 CHAR),
    DESCRICAO           VARCHAR2(200 CHAR),
    GRAVIDADE           VARCHAR2(12 CHAR),
    PONTOS              NUMBER(2),
    VALOR               NUMBER(10,2),
    PRAZO_DEFESA        DATE,
    VENCIMENTO_BOLETO   DATE,
    CONSTRAINT PK_MULTAS           PRIMARY KEY (ID),
    -- AIT e unico por natureza. O UNIQUE tambem evita cadastrar a mesma multa duas vezes.
    CONSTRAINT UK_MULTAS_AIT       UNIQUE (AIT),
    CONSTRAINT FK_MULTAS_VEICULO   FOREIGN KEY (VEICULO_ID)
        REFERENCES VEICULOS (ID),
    CONSTRAINT CK_MULTAS_GRAVIDADE CHECK (GRAVIDADE IN ('LEVE','MEDIA','GRAVE','GRAVISSIMA')),
    CONSTRAINT CK_MULTAS_PONTOS    CHECK (PONTOS BETWEEN 0 AND 7)
);

COMMENT ON TABLE MULTAS IS 'Auto de infracao. Exige veiculo cadastrado (RF-16b).';
COMMENT ON COLUMN MULTAS.LOCAL_INFRACAO IS 'LOCAL sozinho e palavra reservada do Oracle.';
COMMENT ON COLUMN MULTAS.GRAVIDADE IS 'Define o preco do servico e sustenta a contagem de pontos.';
COMMENT ON COLUMN MULTAS.ENQUADRAMENTO IS 'Artigo do CTB citado no recurso, ex. 218 I.';


-- Suspensao e cassacao nao tem AIT nem veiculo: correm contra o condutor.
-- Por isso vivem em tabela propria, ligadas ao cliente.
CREATE TABLE PROCESSOS_CNH (
    ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLIENTE_ID         NUMBER             NOT NULL,
    NUMERO_PROCESSO    VARCHAR2(30 CHAR)  NOT NULL,
    TIPO               VARCHAR2(12 CHAR)  NOT NULL,
    MOTIVO             VARCHAR2(200 CHAR),
    DATA_NOTIFICACAO   DATE,
    PRAZO_DEFESA       DATE,
    PORTARIA           VARCHAR2(50 CHAR),
    ORGAO_INSTAURADOR  VARCHAR2(80 CHAR),
    CONSTRAINT PK_PROCESSOS_CNH         PRIMARY KEY (ID),
    CONSTRAINT UK_PROCESSOS_CNH_NUMERO  UNIQUE (NUMERO_PROCESSO),
    CONSTRAINT FK_PROCESSOS_CNH_CLIENTE FOREIGN KEY (CLIENTE_ID)
        REFERENCES CLIENTES (ID),
    CONSTRAINT CK_PROCESSOS_CNH_TIPO    CHECK (TIPO IN ('SUSPENSAO','CASSACAO'))
);

COMMENT ON TABLE PROCESSOS_CNH IS 'Processo administrativo de suspensao ou cassacao do direito de dirigir.';
COMMENT ON COLUMN PROCESSOS_CNH.NUMERO_PROCESSO IS 'Numero que o DETRAN da na notificacao, ex. 50227/2026.';
COMMENT ON COLUMN PROCESSOS_CNH.PRAZO_DEFESA IS 'Contado da notificacao, e nao da data de uma infracao.';


-- A suspensao por pontuacao ataca cada multa que formou a pontuacao.
CREATE TABLE PROCESSO_MULTA (
    PROCESSO_CNH_ID  NUMBER  NOT NULL,
    MULTA_ID         NUMBER  NOT NULL,
    OBSERVACAO       VARCHAR2(400 CHAR),
    CONSTRAINT PK_PROCESSO_MULTA          PRIMARY KEY (PROCESSO_CNH_ID, MULTA_ID),
    CONSTRAINT FK_PROCMULTA_PROCESSO      FOREIGN KEY (PROCESSO_CNH_ID)
        REFERENCES PROCESSOS_CNH (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PROCMULTA_MULTA         FOREIGN KEY (MULTA_ID)
        REFERENCES MULTAS (ID)
);

COMMENT ON TABLE PROCESSO_MULTA IS 'Multas que compoem a pontuacao questionada num processo de suspensao.';


-- =====================================================================
-- 4. SERVICOS E PRECOS
-- =====================================================================

CREATE TABLE TIPOS_SERVICO (
    ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME            VARCHAR2(80 CHAR)  NOT NULL,
    TEM_INSTANCIAS  CHAR(1)            DEFAULT 'N' NOT NULL,
    VALOR_TABELA    NUMBER(10,2)       NOT NULL,
    ATIVO           CHAR(1)            DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_TIPOS_SERVICO       PRIMARY KEY (ID),
    CONSTRAINT UK_TIPOS_SERVICO_NOME  UNIQUE (NOME),
    CONSTRAINT CK_TIPOS_SERVICO_INST  CHECK (TEM_INSTANCIAS IN ('S','N')),
    CONSTRAINT CK_TIPOS_SERVICO_ATIVO CHECK (ATIVO IN ('S','N')),
    CONSTRAINT CK_TIPOS_SERVICO_VALOR CHECK (VALOR_TABELA >= 0)
);

COMMENT ON TABLE TIPOS_SERVICO IS 'Tabela de precos. TEM_INSTANCIAS diz se o servico percorre autuacao, JARI e CETRAN.';


-- O roteiro de um servico direto: reciclagem, renovacao de CNH, Uber.
CREATE TABLE ETAPAS_MODELO (
    ID               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TIPO_SERVICO_ID  NUMBER             NOT NULL,
    ORDEM            NUMBER(2)          NOT NULL,
    NOME             VARCHAR2(120 CHAR) NOT NULL,
    CONSTRAINT PK_ETAPAS_MODELO       PRIMARY KEY (ID),
    CONSTRAINT UK_ETAPAS_MODELO_ORDEM UNIQUE (TIPO_SERVICO_ID, ORDEM),
    CONSTRAINT FK_ETAPAS_MODELO_TIPO  FOREIGN KEY (TIPO_SERVICO_ID)
        REFERENCES TIPOS_SERVICO (ID) ON DELETE CASCADE
);

COMMENT ON TABLE ETAPAS_MODELO IS 'Passos previstos de cada servico direto, na ordem.';


-- =====================================================================
-- 5. CONTRATACAO E EXECUCAO
-- =====================================================================

-- O "pedido". O desconto fica aqui porque ela fecha preco pelo conjunto:
-- "20 multas, fecho por tanto".
CREATE TABLE CONTRATACOES (
    ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLIENTE_ID         NUMBER              NOT NULL,
    DATA_CONTRATACAO   DATE                DEFAULT SYSDATE NOT NULL,
    VALOR_TABELA       NUMBER(10,2)        DEFAULT 0 NOT NULL,
    DESCONTO           NUMBER(10,2)        DEFAULT 0 NOT NULL,
    VALOR_FINAL        NUMBER(10,2)        NOT NULL,
    SITUACAO           VARCHAR2(20 CHAR)   DEFAULT 'ANDAMENTO' NOT NULL,
    OBSERVACOES        VARCHAR2(500 CHAR),
    CONSTRAINT PK_CONTRATACOES          PRIMARY KEY (ID),
    CONSTRAINT FK_CONTRATACOES_CLIENTE  FOREIGN KEY (CLIENTE_ID)
        REFERENCES CLIENTES (ID),
    CONSTRAINT CK_CONTRATACOES_SITUACAO CHECK (SITUACAO IN ('ANDAMENTO','CONCLUIDO','CANCELADO')),
    CONSTRAINT CK_CONTRATACOES_VALORES  CHECK (VALOR_TABELA >= 0 AND DESCONTO >= 0 AND VALOR_FINAL >= 0)
);

COMMENT ON TABLE CONTRATACOES IS 'Servicos fechados com o cliente numa negociacao.';
COMMENT ON COLUMN CONTRATACOES.VALOR_TABELA IS 'Soma dos itens antes do desconto. Guardado separado a pedido dela (Q42).';
COMMENT ON COLUMN CONTRATACOES.VALOR_FINAL IS 'O combinado. E dele que sai o valor em aberto.';


-- Cada servico dentro da contratacao. Vinte multas viram vinte itens.
CREATE TABLE ITENS_CONTRATACAO (
    ID               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CONTRATACAO_ID   NUMBER             NOT NULL,
    TIPO_SERVICO_ID  NUMBER             NOT NULL,
    MULTA_ID         NUMBER,
    PROCESSO_CNH_ID  NUMBER,
    SITUACAO         VARCHAR2(20 CHAR)  DEFAULT 'ANDAMENTO' NOT NULL,
    CONSTRAINT PK_ITENS_CONTRATACAO       PRIMARY KEY (ID),
    CONSTRAINT FK_ITENS_CONTRATACAO       FOREIGN KEY (CONTRATACAO_ID)
        REFERENCES CONTRATACOES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITENS_TIPO_SERVICO      FOREIGN KEY (TIPO_SERVICO_ID)
        REFERENCES TIPOS_SERVICO (ID),
    CONSTRAINT FK_ITENS_MULTA             FOREIGN KEY (MULTA_ID)
        REFERENCES MULTAS (ID),
    CONSTRAINT FK_ITENS_PROCESSO_CNH      FOREIGN KEY (PROCESSO_CNH_ID)
        REFERENCES PROCESSOS_CNH (ID),
    CONSTRAINT CK_ITENS_SITUACAO          CHECK (SITUACAO IN ('ANDAMENTO','CONCLUIDO','CANCELADO')),
    -- Um item e sobre uma multa OU sobre um processo de CNH, nunca os dois.
    CONSTRAINT CK_ITENS_ORIGEM_UNICA      CHECK (MULTA_ID IS NULL OR PROCESSO_CNH_ID IS NULL)
);

COMMENT ON TABLE ITENS_CONTRATACAO IS 'Um servico contratado. Aponta para a multa ou para o processo de CNH.';


-- As fases do recurso. Linha por fase, e nao coluna por fase: e o que
-- permite guardar o historico de um processo que dura tres anos.
CREATE TABLE INSTANCIAS (
    ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ITEM_ID             NUMBER              NOT NULL,
    FASE                VARCHAR2(12 CHAR)   NOT NULL,
    SITUACAO            VARCHAR2(30 CHAR)   DEFAULT 'CONTRATADO' NOT NULL,
    PRAZO_PROTOCOLO     DATE,
    DATA_PROTOCOLO      DATE,
    NUMERO_PROTOCOLO    VARCHAR2(50 CHAR),
    ORGAO_DESTINATARIO  VARCHAR2(120 CHAR),
    DATA_RESULTADO      DATE,
    RESULTADO           VARCHAR2(12 CHAR),
    OBSERVACOES         VARCHAR2(500 CHAR),
    CONSTRAINT PK_INSTANCIAS          PRIMARY KEY (ID),
    CONSTRAINT UK_INSTANCIAS_ITEM_FASE UNIQUE (ITEM_ID, FASE),
    CONSTRAINT FK_INSTANCIAS_ITEM     FOREIGN KEY (ITEM_ID)
        REFERENCES ITENS_CONTRATACAO (ID) ON DELETE CASCADE,
    CONSTRAINT CK_INSTANCIAS_FASE     CHECK (FASE IN ('AUTUACAO','JARI','CETRAN')),
    -- ANULADO: a fase caiu sem julgamento e o processo seguiu na seguinte.
    CONSTRAINT CK_INSTANCIAS_RESULT   CHECK (RESULTADO IN ('DEFERIDO','INDEFERIDO','ANULADO')),
    CONSTRAINT CK_INSTANCIAS_SITUACAO CHECK (SITUACAO IN (
        'CONTRATADO',
        'AGUARDANDO_DOCUMENTO',
        'AGUARDANDO_PROTOCOLO_JARI',
        'AGUARDANDO_PROTOCOLO_CETRAN',
        'PROTOCOLADO',
        'AGUARDANDO_JULGAMENTO',
        'DEFERIDO',
        'INDEFERIDO',
        'CANCELADO',
        'DESISTENCIA',
        'PRAZO_PERDIDO',
        'ANULADO'))
);

COMMENT ON TABLE INSTANCIAS IS 'Fase do recurso: autuacao (defesa previa), JARI e CETRAN.';
COMMENT ON COLUMN INSTANCIAS.ORGAO_DESTINATARIO IS 'Muda por fase e por tipo: prefeitura, JARI ou DETRAN.';


-- A execucao do roteiro de um servico direto.
CREATE TABLE ETAPAS (
    ID                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ITEM_ID           NUMBER   NOT NULL,
    ETAPA_MODELO_ID   NUMBER   NOT NULL,
    CONCLUIDA         CHAR(1)  DEFAULT 'N' NOT NULL,
    DATA_CONCLUSAO    DATE,
    CONSTRAINT PK_ETAPAS            PRIMARY KEY (ID),
    CONSTRAINT UK_ETAPAS_ITEM       UNIQUE (ITEM_ID, ETAPA_MODELO_ID),
    CONSTRAINT FK_ETAPAS_ITEM       FOREIGN KEY (ITEM_ID)
        REFERENCES ITENS_CONTRATACAO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ETAPAS_MODELO     FOREIGN KEY (ETAPA_MODELO_ID)
        REFERENCES ETAPAS_MODELO (ID),
    CONSTRAINT CK_ETAPAS_CONCLUIDA  CHECK (CONCLUIDA IN ('S','N'))
);

COMMENT ON TABLE ETAPAS IS 'Checklist do servico direto para um item especifico.';


-- =====================================================================
-- 6. DINHEIRO
-- =====================================================================

CREATE TABLE PAGAMENTOS (
    ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CONTRATACAO_ID  NUMBER             NOT NULL,
    DATA_PAGAMENTO  DATE               DEFAULT SYSDATE NOT NULL,
    VALOR           NUMBER(10,2)       NOT NULL,
    FORMA           VARCHAR2(20 CHAR)  NOT NULL,
    PARCELAS        NUMBER(2)          DEFAULT 1 NOT NULL,
    OBSERVACAO      VARCHAR2(200 CHAR),
    CONSTRAINT PK_PAGAMENTOS           PRIMARY KEY (ID),
    CONSTRAINT FK_PAGAMENTOS_CONTRAT   FOREIGN KEY (CONTRATACAO_ID)
        REFERENCES CONTRATACOES (ID),
    CONSTRAINT CK_PAGAMENTOS_VALOR     CHECK (VALOR > 0),
    CONSTRAINT CK_PAGAMENTOS_PARCELAS  CHECK (PARCELAS BETWEEN 1 AND 12),
    CONSTRAINT CK_PAGAMENTOS_FORMA     CHECK (FORMA IN (
        'DINHEIRO','PIX','PIX_PARCELADO','DEBITO','CREDITO'))
);

COMMENT ON TABLE PAGAMENTOS IS 'Cada entrada de dinheiro. Varias por contratacao: ela aceita pagar em partes.';
COMMENT ON COLUMN PAGAMENTOS.PARCELAS IS 'So para credito. O valor entra integral para o escritorio.';


CREATE TABLE DESPESAS (
    ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CONTRATACAO_ID  NUMBER             NOT NULL,
    TIPO            VARCHAR2(60 CHAR)  NOT NULL,
    VALOR           NUMBER(10,2)       NOT NULL,
    DATA_DESPESA    DATE               DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_DESPESAS          PRIMARY KEY (ID),
    CONSTRAINT FK_DESPESAS_CONTRAT  FOREIGN KEY (CONTRATACAO_ID)
        REFERENCES CONTRATACOES (ID),
    CONSTRAINT CK_DESPESAS_VALOR    CHECK (VALOR >= 0)
);

COMMENT ON TABLE DESPESAS IS 'Custos do servico: correio, taxa de DETRAN. Servem para saber o lucro real.';


CREATE TABLE CREDITOS (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLIENTE_ID  NUMBER             NOT NULL,
    VALOR       NUMBER(10,2)       NOT NULL,
    ORIGEM      VARCHAR2(200 CHAR),
    UTILIZADO   CHAR(1)            DEFAULT 'N' NOT NULL,
    DATA_CREDITO DATE              DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CREDITOS            PRIMARY KEY (ID),
    CONSTRAINT FK_CREDITOS_CLIENTE    FOREIGN KEY (CLIENTE_ID)
        REFERENCES CLIENTES (ID),
    CONSTRAINT CK_CREDITOS_UTILIZADO  CHECK (UTILIZADO IN ('S','N')),
    CONSTRAINT CK_CREDITOS_VALOR      CHECK (VALOR > 0)
);

COMMENT ON TABLE CREDITOS IS 'Devolucao que fica como credito para o cliente usar depois.';


-- =====================================================================
-- 7. ARQUIVOS E ROTINA
-- =====================================================================

CREATE TABLE ARQUIVOS (
    ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLIENTE_ID     NUMBER              NOT NULL,
    INSTANCIA_ID   NUMBER,
    TIPO           VARCHAR2(30 CHAR)   NOT NULL,
    NOME_ARQUIVO   VARCHAR2(200 CHAR)  NOT NULL,
    CAMINHO        VARCHAR2(400 CHAR)  NOT NULL,
    DATA_UPLOAD    DATE                DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_ARQUIVOS           PRIMARY KEY (ID),
    CONSTRAINT FK_ARQUIVOS_CLIENTE   FOREIGN KEY (CLIENTE_ID)
        REFERENCES CLIENTES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ARQUIVOS_INSTANCIA FOREIGN KEY (INSTANCIA_ID)
        REFERENCES INSTANCIAS (ID),
    CONSTRAINT CK_ARQUIVOS_TIPO      CHECK (TIPO IN (
        'CNH','PROCURACAO','CRLV','COMPROVANTE_ENDERECO',
        'COMPROVANTE_PAGAMENTO','COMPROVANTE_PROTOCOLO','NOTIFICACAO','OUTRO'))
);

COMMENT ON TABLE ARQUIVOS IS 'Anexos do cliente. CAMINHO guarda onde o arquivo esta, nao o arquivo.';


-- Prazo, compromisso e tarefa planejada sao a mesma coisa para quem usa:
-- algo com data que precisa acontecer. Por isso uma tabela so.
CREATE TABLE AGENDA (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DATA_AGENDA   DATE                NOT NULL,
    HORA          VARCHAR2(5 CHAR),
    TIPO          VARCHAR2(20 CHAR)   NOT NULL,
    TITULO        VARCHAR2(200 CHAR)  NOT NULL,
    CLIENTE_ID    NUMBER,
    INSTANCIA_ID  NUMBER,
    CONCLUIDO     CHAR(1)             DEFAULT 'N' NOT NULL,
    RECORRENCIA   VARCHAR2(12 CHAR)   DEFAULT 'NENHUMA' NOT NULL,
    OBSERVACAO    VARCHAR2(500 CHAR),
    CONSTRAINT PK_AGENDA             PRIMARY KEY (ID),
    CONSTRAINT FK_AGENDA_CLIENTE     FOREIGN KEY (CLIENTE_ID)
        REFERENCES CLIENTES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_AGENDA_INSTANCIA   FOREIGN KEY (INSTANCIA_ID)
        REFERENCES INSTANCIAS (ID) ON DELETE CASCADE,
