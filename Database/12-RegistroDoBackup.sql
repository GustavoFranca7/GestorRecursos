-- =====================================================================
-- GESTOR DE RECURSOS - registro das execucoes do backup
-- =====================================================================
-- Rodar como GESTOR, nos DOIS bancos: primeiro no de teste, depois no de
-- producao. Enquanto nao rodar, nada quebra: o painel simplesmente nao
-- mostra o aviso, e o backup imprime "registro nao gravado" no log.
--
-- POR QUE
--
-- O backup roda no Agendador de Tarefas de UMA maquina, as 20:00 do
-- domingo. Se a tarefa for desativada, a senha do banco mudar, a pasta do
-- Drive sair do lugar ou a wallet expirar, o backup para de rodar e NADA
-- avisa. O ultimo .zip fica na pasta, com data antiga, e a pasta parece
-- igual a de sempre.
--
-- O Always Free nao tem restauracao a ponto no tempo. Semana sem backup e
-- semana de dado sem segunda copia - e descobrir isso em marco, com o
-- ultimo arquivo de novembro, e o pior caso do sistema inteiro.
--
-- Esta tabela e o que permite o programa avisar. O backup grava uma linha
-- ao terminar; a tela compara a data da ultima linha com hoje.
--
-- POR QUE NO BANCO, E NAO LENDO A PASTA
--
-- A pasta do backup existe na maquina que roda a tarefa. O programa roda
-- em outra - e e justamente nela que o aviso precisa aparecer, porque e a
-- que fica aberta todo dia. O banco e o unico lugar que as duas veem.
--
-- De quebra, a linha so e gravada se o backup conseguiu conversar com o
-- banco: um backup que falhou na conexao nao mente dizendo que rodou.
--
-- O QUE MUDA
--
-- Entra a tabela BACKUPS, e o privilegio dela para o usuario ESTACAO.
-- Nenhuma tabela existente e tocada. A tabela entra sozinha no backup
-- semanal, que descobre as tabelas pelo proprio esquema - nao ha lista
-- para atualizar.
--
-- O passo 4, do privilegio, e o que faz a producao funcionar. Ler a
-- explicacao la antes de pular.
--
-- COMO RODAR
--
-- No SQL Developer Web, "Executar script" (F5), nao "Executar instrucao".
-- =====================================================================

SET SERVEROUTPUT ON;

-- ---------------------------------------------------------------------
-- 1. A tabela
-- ---------------------------------------------------------------------
-- Dentro de bloco com conferencia para o script poder rodar duas vezes
-- sem erro - o que acontece quando alguem nao lembra se ja rodou.
--
-- E historico, nao linha unica: uma linha por execucao. Guardar so a
-- ultima responderia "quando foi o ultimo backup" e nada mais; com o
-- historico da para ver que ele rodou em 12 de 12 domingos, ou que parou
-- em outubro e voltou em novembro.

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe
      FROM USER_TABLES
     WHERE TABLE_NAME = 'BACKUPS';

    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE BACKUPS (
                ID               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                QUANDO           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
                MAQUINA          VARCHAR2(60),
                TABELAS          NUMBER(4)     DEFAULT 0 NOT NULL,
                LINHAS           NUMBER(10)    DEFAULT 0 NOT NULL,
                BYTES            NUMBER(12)    DEFAULT 0 NOT NULL,
                DOCUMENTOS_NOVOS NUMBER(6)     DEFAULT 0 NOT NULL,
                FALHAS           NUMBER(4)     DEFAULT 0 NOT NULL,
                CONSTRAINT PK_BACKUPS PRIMARY KEY (ID)
            )
        ]';
        DBMS_OUTPUT.PUT_LINE('BACKUPS criada.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('BACKUPS ja existia.');
    END IF;
END;
/


-- ---------------------------------------------------------------------
-- 2. O indice da pergunta que a tela faz
-- ---------------------------------------------------------------------
-- A consulta do painel e sempre "a linha mais recente". Sao poucas linhas
-- por ano, mas o indice e barato e deixa a leitura do painel constante.

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe
      FROM USER_INDEXES
     WHERE INDEX_NAME = 'IX_BACKUPS_QUANDO';

    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_BACKUPS_QUANDO ON BACKUPS (QUANDO DESC)';
        DBMS_OUTPUT.PUT_LINE('IX_BACKUPS_QUANDO criado.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('IX_BACKUPS_QUANDO ja existia.');
    END IF;
END;
/


-- ---------------------------------------------------------------------
-- 3. Os comentarios
-- ---------------------------------------------------------------------

COMMENT ON TABLE BACKUPS IS 'Uma linha por execucao do backup semanal. O painel compara a mais recente com hoje para avisar quando a copia parou.';

COMMENT ON COLUMN BACKUPS.QUANDO IS 'Quando o backup terminou, no relogio da maquina que rodou - nao no do banco.';

COMMENT ON COLUMN BACKUPS.MAQUINA IS 'Nome do computador que rodou. Serve para ver se mudou de maquina sem ninguem avisar.';

COMMENT ON COLUMN BACKUPS.BYTES IS 'Tamanho do .zip gravado. Cair de repente e sinal de backup truncado.';

COMMENT ON COLUMN BACKUPS.DOCUMENTOS_NOVOS IS 'Anexos copiados para o espelho nesta execucao. Zero e normal: a semana pode nao ter tido anexo novo.';

COMMENT ON COLUMN BACKUPS.FALHAS IS 'Documentos que nao foram copiados. Maior que zero significa backup do texto gravado, mas acervo incompleto.';


-- ---------------------------------------------------------------------
-- 4. O acesso da estacao
-- ---------------------------------------------------------------------
-- ESTE PASSO E OBRIGATORIO NA PRODUCAO. Sem ele a tabela existe e o
-- programa nao enxerga: ORA-00942, "a tabela ou view nao existe".
--
-- Na producao o programa NAO conecta como GESTOR. Conecta como ESTACAO,
-- que nao tem tabela propria e alcanca as do GESTOR por privilegio
-- concedido uma a uma (ver 08-UsuarioDaEstacao.sql). Aquele script
-- percorreu as tabelas que existiam NAQUELE dia: tabela criada depois
-- nasce invisivel para a estacao ate receber o seu GRANT.
--
-- Os scripts 10 e 11 nao passaram por isto porque mexeram em tabela ja
-- existente, que ja tinha o privilegio. Esta e a primeira tabela nova
-- desde a separacao dos usuarios. A proxima vai precisar do mesmo bloco.
--
-- No banco de teste nao existe ESTACAO: o bloco percebe e nao faz nada.

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM ALL_USERS WHERE USERNAME = 'ESTACAO';

    IF v_existe = 0 THEN
        DBMS_OUTPUT.PUT_LINE('ESTACAO nao existe aqui (e o caso do banco de teste). Nada a liberar.');
    ELSE
        EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE, DELETE ON BACKUPS TO ESTACAO';
        DBMS_OUTPUT.PUT_LINE('BACKUPS liberada para ESTACAO.');

        -- A coluna IDENTITY tem sequence propria, com nome gerado pelo
        -- banco (ISEQ$$_nnnnn). Sem SELECT nela o INSERT falha ao pedir
        -- o proximo numero.
        FOR s IN (SELECT SEQUENCE_NAME
                    FROM USER_TAB_IDENTITY_COLS
                   WHERE TABLE_NAME = 'BACKUPS') LOOP
            EXECUTE IMMEDIATE 'GRANT SELECT ON ' || s.SEQUENCE_NAME || ' TO ESTACAO';
            DBMS_OUTPUT.PUT_LINE('Sequence ' || s.SEQUENCE_NAME || ' liberada para ESTACAO.');
        END LOOP;
    END IF;
END;
/


-- ---------------------------------------------------------------------
-- 5. Depois: conferencia
-- ---------------------------------------------------------------------
-- As oito colunas precisam aparecer, e a tabela sai vazia: a primeira
-- linha entra na proxima execucao do backup, domingo as 20:00.

SELECT COLUMN_NAME, DATA_TYPE, NULLABLE, DATA_DEFAULT
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME = 'BACKUPS'
 ORDER BY COLUMN_ID;

SELECT COUNT(*) AS EXECUCOES_REGISTRADAS FROM BACKUPS;

-- Na producao: precisa aparecer BACKUPS com os quatro direitos, mais a
-- sequence com SELECT. No teste esta consulta volta vazia, e esta certo.

SELECT TABLE_NAME, LISTAGG(PRIVILEGE, ', ') WITHIN GROUP (ORDER BY PRIVILEGE) AS DIREITOS
  FROM USER_TAB_PRIVS_MADE
 WHERE GRANTEE = 'ESTACAO'
   AND (TABLE_NAME = 'BACKUPS'
        OR TABLE_NAME IN (SELECT SEQUENCE_NAME FROM USER_TAB_IDENTITY_COLS
                           WHERE TABLE_NAME = 'BACKUPS'))
 GROUP BY TABLE_NAME
 ORDER BY TABLE_NAME;
